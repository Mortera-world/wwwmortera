        let isSpanish = localStorage.getItem('lang') !== 'en';

        function updateLanguage() {
            document.getElementById('terms-es').classList.toggle('hidden', !isSpanish);
            document.getElementById('terms-en').classList.toggle('hidden', isSpanish);
            document.getElementById('title').innerText = isSpanish ? 'Terminos y Condiciones' : 'Terms and Conditions';
            document.getElementById('accept-text').innerText = isSpanish ? 'Acepto los terminos y condiciones' : 'I accept the terms and conditions';
            document.getElementById('toggle-lang').innerText = isSpanish ? 'Eng' : 'Esp';
        }

        function toggleLanguage() {
            isSpanish = !isSpanish;
            localStorage.setItem('lang', isSpanish ? 'es' : 'en');
            updateLanguage();
        }

        document.getElementById('accept').addEventListener('change', function() {
            document.getElementById('continue').disabled = !this.checked;
        });

        document.getElementById('continue').addEventListener('click', function() {
            window.location.href = '?points';
        });

        updateLanguage();
