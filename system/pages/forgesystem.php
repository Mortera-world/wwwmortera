<div>Ambos tipos de criaturas producen<img style="border:0px;" src="/images/forge/Dust.gif"> <b>Dusts</b> una vez muerto, pero solo las <b>criaturas diabólicas</b> producen <img style="border:0px;" src="/images/forge/Sliver.gif"> <b>Slivers</b>. Así como estas <b>criaturas influenciadas</b> son <b>más fuertes</b>, producen más polvo cuanto más acumulaciones tienen.</div>
<br>
<div>Ambos recursos se utilizan en la <b>Forja de la Exaltación</b>.<br> También puedes transformar tu <img style="border:0px;" src="/images/forge/Dust.gif"> <b>Dust</b> en <b>Slivers (30 Dust para 30 Slivers)</b>, y tus <b>Slivers</b> en <img style="border:0px;" src="/images/forge/Exalted_Core.gif"> <b>Exalted Cores (50 Slivers para 1 Core)</b>.</div>
<br>
<div>Al matar una criatura <b>diabólica</b> o <b>influenciada</b>, se otorga la misma cantidad de <b>polvo</b> a todos los miembros del grupo que actualmente tengan party shared y se encuentren dentro de exp. distancia de rango compartido (es decir, menor o igual a 30 campos, en el mismo piso o un piso arriba/abajo). <b>Cada miembro del grupo recibe la misma cantidad</b> de polvo que recibiría un solo jugador si matara a la criatura solo, sin estar en un grupo. En otras palabras, no hay ningún inconveniente en "compartir" Dust de esta manera.</div>
<br>
<div><b>La cantidad de polvo recibido depende de la cantidad de acumulaciones que tenga la criatura, y por cada acumulación, los jugadores recibirán de 10 a 80 polvos. Al igual que su fuerza, una criatura diabólica produce polvo por 15 pilas.</b></div>
