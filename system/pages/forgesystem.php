<p>El sistema de <strong>Exaltation Forge</strong> tiene como objetivo otorgar 3 habilidades diferentes</p>
<p>Funcionan de manera similar y al mismo tiempo en conjunto con Encantamientos e Imbuiciones. Sin embargo, con una diferencia para los Charms, que sería el hecho de que se pueden usar sobre cualquier criatura o personaje (no hay necesidad de "seleccionar" qué criatura activar) y también una diferencia para los Imbuements, que sería el hecho de que no tienen una duración.</p>
<p>Para acceder al Sistema de Exaltación, simplemente dirígete a la <strong>Forja de Exaltación</strong> ubicada en <strong>Adventurers' Guild</strong>.</p>
<p>Estas 3 habilidades mencionadas anteriormente se pueden usar solo en 3 categorías de elementos, que son Armas, Armadura y Cascos. Cada elemento mejorable tiene una Calificación que va del 1 al 4. Estas habilidades otorgan diferentes efectos y son:</p>
