	  <br>
	  <div style="text-align: justify; font-size: 16px; line-height: 1.5;"><strong>Fusión:</strong> Se pueden fusionar dos ítems iguales para aumentar el <strong><span style="color: red;">Tier</span></strong> de uno de ellos. Los dos ítems deben ser iguales, tener el mismo <strong><span style="color: red;">Tier</span></strong> y no pueden estar imbuidos. Además, necesitarás <strong><span style="color: red;">100 dust</span></strong><img src="/images/forge/Dust.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;"> por cada intento, <strong><span style="color: red;">Exalted Core</span></strong><img src="/images/forge/Exalted_Core.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;">que son opcionales y <strong><span style="color: red;">Dinero</span></strong>; el precio para subir el Tier varía de acuerdo a la clasificación y aumenta según el <strong><span style="color: red;">Tier</span></strong> en el que se encuentre el ítem.<br>

<strong><span style="color: red;">Si la fusion es exitosa</span></strong>, el <strong><span style="color: red;">Tier</span></strong> de uno de los ítems aumentará, mientras que el segundo ítem se consumirá. Es decir, que si tenías 2 armaduras <strong><span style="color: red;">Tier</span></strong> 1 y las fusionas, únicamente obtendrás 1 armadura <strong><span style="color: red;">Tier</span></strong> 2.
Para aumentar tus posibilidades en la forja, podrás usar una <strong><span style="color: red;">Exalted Core</span></strong><img src="/images/forge/Exalted_Core.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;"> para incrementar de 50% a 80% la posibilidad de éxito en la fusión.<br>

<strong><span style="color: red;">Si la fusion falla</span></strong>, uno de los ítems permanece sin cambios. El <strong><span style="color: red;">Tier</span></strong> del segundo ítem se reducirá en uno. Si el ítem no tenía <strong><span style="color: red;">Tier</span></strong>, se consumirá. Esto quiere decir que si tenías 2 armaduras sin <strong><span style="color: red;">Tier</span></strong>y las intentas subir a <strong><span style="color: red;">Tier</span></strong> 1, al fallar, una de ellas desaparecerá.<br>
Para reducir tus pérdidas en la forja, podrás usar una <strong><span style="color: red;">Exalted Core</span></strong><img src="/images/forge/Exalted_Core.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;"> para disminuir de <strong><span style="color: red;">100%</span></strong> a <strong><span style="color: red;">50%</span></strong> la posibilidad de que uno de los ítem sin <strong><span style="color: red;">Tier</span></strong> se rompa, o que uno de los ítems con <strong><span style="color: red;">Tier</span></strong> pierda un nivel.
<br>
<br>
Además, al ser anunciado el resultado de la fusión hay una pequeña posibilidad de que te ocurra uno de los siguientes bonus de suerte:
<br>
<strong><span style="color: red;">1.-</span></strong> El segundo ítem no se consume en el proceso.
<br>
<strong><span style="color: red;">2.-</span></strong> El dinero no se consume en el proceso.
<br>
<strong><span style="color: red;">3.-</span></strong> Los <strong><span style="color: red;">100 dust</span></strong><img src="/images/forge/Dust.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;"> no se consumen en el proceso.
<br>
<strong><span style="color: red;">4.-</span></strong> Las <strong><span style="color: red;">Exalted Core</span></strong><img src="/images/forge/Exalted_Core.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;"> no se consumen en el proceso.
<br>
<strong><span style="color: red;">5.-</span></strong> El ítem fusionado gana 2 <strong><span style="color: red;">Tier</span></strong> en lugar de 1.
<br>
<strong><span style="color: red;">6.-</span></strong> El segundo ítem no se consume, pero baja 1 <strong><span style="color: red;">Tier</span></strong>.
<br>
<strong><span style="color: red;">7.-</span></strong> Obtendrás 2 ítems del mismo <strong><span style="color: red;">Tier</span></strong>.
<br>
<br>
<strong><span style="color: red;">Transferencia de Tier:</span></strong>: Para transferir un <strong><span style="color: red;">Tier</span></strong> a otro ítem, necesita dos ítem de la misma clasificación, <strong><span style="color: red;">100 dust</span></strong><img src="/images/forge/Dust.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;">  1 <strong><span style="color: red;">Exalted Core</span></strong><img src="/images/forge/Exalted_Core.gif" style="border:0px; width: 32px; height: auto; vertical-align: middle;">  y dinero. Ten en cuenta que los ítem imbuidos no se pueden usar para una transferencia. Uno de los dos ítem debe tener al menos <strong><span style="color: red;">Tier</span></strong> 2. Este ítem se consumirá durante la transferencia junto con los recursos necesarios. El otro ítem no debe tener <strong><span style="color: red;">Tier</span></strong> y recibirá el <strong><span style="color: red;">Tier</span></strong> del ítem consumido reducido en uno. Esto significa que, los únicos ítems que pueden recibir una transferencia de <strong><span style="color: red;">Tier</span></strong>, son aquellos que no tengan <strong><span style="color: red;">Tier</span></strong>.</div>
