Próximamente se añadirán al servidor las nuevas armas Ethereals, una categoría de equipamiento superior a las actuales armas Ultimatum. Estas nuevas armas estarán diseñadas para ofrecer un poder mucho mayor, convirtiéndose en el nuevo nivel máximo de armamento disponible.

¿Cómo se crean las armas Ethereals?
Para poder fabricar un arma Ethereal será necesario reunir los siguientes materiales:

5 armas Ultimatum del mismo tipo
Ejemplo: si deseas crear una espada Ethereal, deberás utilizar 5 espadas Ultimatum.
1 Activator Ring  - 61918
1 Channeler - 61928
Una vez tengas todos los materiales requeridos, podrás utilizar el siguiente comando para realizar el proceso de fabricación:

 
!ultimatumplus craft
 
Este mismo comando también servirá para convertir y utilizar los materiales necesarios durante el proceso.

¿Cómo conseguir el Activator Ring y el Channeler?
Inicialmente, estos objetos especiales podrán conseguirse mediante las promociones de donación activas.

Método por donación
Cuando la promoción esté habilitada, los jugadores que realicen una donación de 500 o más podrán obtener:

Activator Ring
Channeler 
Sin embargo, estos objetos no serán exclusivos de las donaciones, ya que también se añadieron métodos para obtenerlos completamente jugando.

Nuevos Respawns y Sistema de Farmeo
Con esta actualización se añadieron nuevos sistemas para que cualquier jugador pueda avanzar hacia las armas Ethereals mediante esfuerzo y farmeo dentro del juego.

Nuevo Respawn: Skeleton King- looktype 1815
Se añadió un nuevo respawn llamado Skeleton King.

Este boss tendrá una probabilidad de otorgar un nuevo objeto llamado:

Mystical Fragment - 49457
Los jugadores deberán reunir:

1000 Mystical Fragments 
Una vez obtenida esta cantidad, podrán convertirlos en un:

Channeler
Nuevo recurso: Sun Essences - 60821
También se añadieron las nuevas:

Sun Essences 
Estas únicamente podrán conseguirse derrotando:

Criaturas influenciadas con más de 8 millones de vida
De igual manera, será necesario reunir:

1000 Sun Essences 
para poder utilizarlas dentro del nuevo sistema de crafteo.

Comando de fabricación
Cuando tengas todos los materiales necesarios, deberás utilizar el siguiente comando:

 
!ultimatumplus craft
 
Con este comando podrás:

Crear armas Ethereals
Convertir materiales especiales
Realizar el proceso de evolución desde Ultimatum hacia Ethereal
Contenido futuro
